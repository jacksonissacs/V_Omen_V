const byId = new Map(events.map((event) => [event.id, event]))

export function getEvent(id: string): AionEvent | undefined {
  return byId.get(id)
}

export function listEvents(): AionEvent[] {
  return events.slice()
}

export function getRelatedEvents(event: AionEvent): AionEvent[] {
  return event.relatedEvents
    .map((id) => byId.get(id))
    .filter((item): item is AionEvent => item !== undefined)
}
